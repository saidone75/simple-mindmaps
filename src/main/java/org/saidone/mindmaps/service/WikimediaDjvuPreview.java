package org.saidone.mindmaps.service;

import lombok.val;

import java.util.Locale;
import java.util.Objects;
import java.util.Set;

/** Uses the preview generated by Wikimedia; never sends the DjVu document to the browser. */
final class WikimediaDjvuPreview {
    private static final Set<String> WEB_MIME_TYPES = Set.of(
            "image/jpeg", "image/png", "image/gif", "image/webp", "image/svg+xml");

    private WikimediaDjvuPreview() {
    }

    static boolean isDjvu(String title, String mime, String imageUrl) {
        val loweredMime = Objects.toString(mime, "").toLowerCase(Locale.ROOT);
        if (loweredMime.contains("djvu") || loweredMime.contains("vnd.djvu")) {
            return true;
        }

        val titleOrUrl = (Objects.toString(title, "") + " " + Objects.toString(imageUrl, ""))
                .toLowerCase(Locale.ROOT);
        return Set.of(".djvu", ".djv").stream().anyMatch(titleOrUrl::contains);
    }

    static String resolve(String url, String mime) {
        if (url == null || url.isBlank() || mime == null
                || !WEB_MIME_TYPES.contains(mime.toLowerCase(Locale.ROOT))) {
            return null;
        }
        return url;
    }
}
